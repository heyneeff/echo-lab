#!/usr/bin/env python3
"""gen_styles.py: write dsp/Styles.h from measure/fits/*.json (+ hand-voiced styles below).

  python3 measure/gen_styles.py

Style names are OUR names (the reference style each was fitted to is noted in a comment, for
engineering only; reference names never appear in the plugin).
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# our name  <-  fitted reference profile (order = order in the plugin's Style menu)
ORDER = [
    ("Studio", "Studio Tape"),
    ("Space Tape", "Space Echo"),
    ("Plex", "EchoPlex"),
    ("Memory", "Memory Man"),
    ("Dark Analog", "DM-2"),
    ("Digital", "Digital Delay"),
    ("Radio", "AM Radio"),
    ("ORPHEO", None),  # our signature style: voiced by ear with Neeff (no reference)
]
# The Style list is a FIXED 8 slots: Live stores the choice as a normalized value, so the list
# must never change length or saved sessions would jump to another style.
FIELDS = ["loopHPHz", "loopLPHz", "loopLP2Hz", "loopTiltDb", "shelfHz", "loopPeakHz", "loopPeakDb",
          "loopPeakQ", "wetHPHz", "wetLPHz", "wetLPPoles", "wetBrickHz", "satType", "satDrive",
          "satBias", "satKnee", "wowCents", "wowRateHz", "flutterCents", "flutterRateHz",
          "noiseDb", "noiseLPHz", "outputDb"]
INTS = {"wetLPPoles", "satType"}
# hand-voiced styles (no reference to fit): first sketches, refined by ear with Neeff
VOICED = {
    # ORPHEO v0.1 (Nov 16): warm, slightly worn tape: repeats lose air gently, a little body
    # bump, soft record-head saturation, slow wow + faint flutter, a whisper of hiss. Wide Dual
    # is the flagship preset (set in the face presets).
    "ORPHEO": {"loopHPHz": 90, "loopLPHz": 7800, "loopTiltDb": 1.2, "shelfHz": 3500, "loopPeakHz": 420,
               "loopPeakDb": 0.6, "loopPeakQ": 0.7, "wetHPHz": 60, "wetLPHz": 11500, "wetLPPoles": 2,
               "satType": 3, "satDrive": 1.05, "satBias": 0.02, "satKnee": 0.45, "wowCents": 7,
               "wowRateHz": 0.8, "flutterCents": 2.5, "flutterRateHz": 5.5, "noiseDb": -78,
               "noiseLPHz": 6000, "outputDb": -1.0},
}


def main():
    entries = []
    for ours, ref in ORDER:
        f = os.path.join(HERE, "fits", (ref or "") + ".json")
        if ours in VOICED:
            v = VOICED[ours]
            parts = ['.name = "%s"' % ours] + [".%s = %s" % (k, int(round(v[k])) if k in INTS else "%.6g" % v[k]) for k in FIELDS if k in v]
            entries.append("    {%s},  // voiced by ear (no reference)" % ", ".join(parts))
            continue
        if not ref or not os.path.exists(f):
            entries.append('    {.name = "%s (soon)", .satType = 2},  // placeholder: clean until fitted/voiced' % ours)
            continue
        fit = json.load(open(f))
        v = fit["values"]
        parts = ['.name = "%s"' % ours]
        for k in FIELDS:
            if k in v:
                parts.append(".%s = %s" % (k, int(round(v[k])) if k in INTS else "%.6g" % v[k]))
        entries.append("    {%s},  // fit: total error %.1f" % (", ".join(parts), fit.get("total", -1)))
    out = """// Styles: GENERATED by measure/gen_styles.py from measure/fits/*.json. Do not hand-edit;
// re-run the fit, then the generator.
#pragma once
#include <cstring>
#include "EchoEngine.h"

namespace echolab {

inline const Style kStyles[] = {
%s
};
inline constexpr int kNumStyles = sizeof(kStyles) / sizeof(kStyles[0]);

inline const Style* findStyle(const char* name) {
    for (const auto& s : kStyles) if (!std::strcmp(s.name, name)) return &s;
    return nullptr;
}

}  // namespace echolab
""" % "\n".join(entries)
    open(os.path.join(ROOT, "dsp", "Styles.h"), "w").write(out)
    assert len(entries) == 8, "Style list must stay at 8 slots"
    print("wrote %d styles: %s" % (len(entries), [e.split('"')[1] for e in entries]))


if __name__ == "__main__":
    main()
