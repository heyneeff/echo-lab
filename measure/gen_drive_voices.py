#!/usr/bin/env python3
"""gen_drive_voices.py: write dsp/DriveVoices.h from measure/fits_drive/*.json. FIXED 8 slots
(Live stores the Style choice as a normalized value: the list must never change length)."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ORDER = [("Tape", "A"), ("Desk", "E"), ("Iron", "N"), ("Tube", "T"), ("Pentode", "P"),
         ("Crush", None), ("ORPHEO", None), ("Spare", None)]
FIELDS = ["gainPerDriveDb", "baseGainDb", "ceiling", "knee", "asym", "bias", "biasTrack", "emphHz", "emphDb",
          "lowHz", "highHz", "tiltDb", "invert", "outDb", "punishDb"]


def main():
    rows = []
    for ours, ref in ORDER:
        f = os.path.join(HERE, "fits_drive", "%s.json" % ref) if ref else ""
        if ref and os.path.exists(f):
            fit = json.load(open(f))
            v = fit["voice"]
            parts = ['.name = "%s"' % ours]
            for k in FIELDS:
                if k in v:
                    parts.append(".%s = %s" % (k, ("true" if v[k] else "false") if k == "invert" else "%.6g" % v[k]))
            rows.append("    {%s},  // fit: total %.1f" % (", ".join(parts), fit["total"]))
        elif ours == "Crush":  # voiced by ear later; starts as a hot, lopsided pentode-style clip
            rows.append('    {.name = "Crush", .gainPerDriveDb = 4.0, .baseGainDb = 0, .ceiling = 0.3, .knee = 0.2, '
                        '.asym = 0.25, .bias = 0.12, .emphHz = 2500, .emphDb = 4, .lowHz = 40, .highHz = 14000, '
                        '.tiltDb = 1.5, .outDb = 6, .punishDb = 20},  // voiced (to tune by ear)')
        else:
            rows.append('    {.name = "%s (soon)"},  // placeholder' % ours)
    assert len(rows) == 8
    open(os.path.join(ROOT, "dsp", "DriveVoices.h"), "w").write('''// DriveVoices: GENERATED by measure/gen_drive_voices.py from measure/fits_drive. Fixed 8 slots.
#pragma once
#include "DriveEngine.h"

namespace echolab {

inline const DriveVoice kDriveVoices[] = {
%s
};
inline constexpr int kNumDriveVoices = 8;

}  // namespace echolab
''' % "\n".join(rows))
    print("wrote DriveVoices.h:", [r.split('"')[1] for r in rows])


if __name__ == "__main__":
    main()
